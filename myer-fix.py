def extract_credentials(text, keys):
    """Universal extractor for .env, HTML, JSON, and Python configs."""
    found = {}
    # .env / Config style
    env_regex = r'(?i)\s*(' + '|'.join(keys) + r')\s*=\s*["\']?([^"\n\'\s]+)["\']?\s*'
    env_matches = reg(env_regex, text)
    for k, v in env_matches: found[k.upper()] = v
    # JSON / Python style
    json_regex = r'(?i)[\'"]?(' + '|'.join(keys) + r')[\'"]?\s*[:=]\s*["\']?([^"\']+)["\']?'
    json_matches = reg(json_regex, text)
    for k, v in json_matches: found[k.upper()] = v
    # HTML Table style
    html_key_pattern = r'(?i)<td>(' + '|'.join([k.replace('_', ' ') for k in keys]) + r')<\/td>\s+<td><pre[^>]*>(.*?)<\/span>'
    html_matches = reg(html_key_pattern, text)
    for k, v in html_matches: 
        clean_key = str(k).replace(' ', '_').replace('+', '_').upper()
        found[clean_key] = v
    return found

